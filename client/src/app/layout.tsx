import type { Metadata } from "next"
import { cookies } from "next/headers"
import "./globals.css"
import { byekan, geistMono, geistSans } from "@/utils/fonts/fonts"
import Header from "@/components/Header"
import Footer from "@/components/Footer/Footer"
import Providers from "./providers"
import { cookieNames } from "@/constants/cookies"
import type { User } from "@/types/auth"

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
}

async function getInitialUser(): Promise<User | null> {
  const cookieStore = await cookies()
  const raw = cookieStore.get(cookieNames.user)?.value
  if (!raw) return null
  try {
    return JSON.parse(raw) as User
  } catch {
    return null
  }
}

export default async function RootLayout({ children }: LayoutProps<"/">) {
  const initialUser = await getInitialUser()

  return (
    <html
      lang="fa" dir="rtl"
      className={`${byekan.variable} ${geistSans.variable} ${geistMono.variable} h-full antialiased`}
    >
      <body className="min-h-full flex flex-col font-sans">
        <Providers initialUser={initialUser}>
          <Header />
          {children}
          <Footer/>
        </Providers>
      </body>
    </html>
  )
}
